#include "units/ShitfireUnitAssets.h"
#include "ShitfireGame.h"

#include "Animation/AnimSequence.h"
#include "Engine/SkeletalMesh.h"
#include "Engine/StaticMesh.h"
#include "Materials/MaterialInterface.h"

namespace
{
	template <typename T>
	T* LoadLogged(const TCHAR* Path, const TCHAR* What)
	{
		T* Obj = LoadObject<T>(nullptr, Path);
		if (!Obj)
		{
			UE_LOG(LogShitfire, Warning, TEXT("units: %s missing (%s)"), What, Path);
		}
		return Obj;
	}
}

FShitfireUnitAssets FShitfireUnitAssets::Load()
{
	FShitfireUnitAssets A;

	// Interchange names the skeletal body/head by content hash - stable for a
	// given GLB, regenerated by Tools/import_assets.py. A paid pack lands as
	// new paths right here.
	A.SoldierMesh = LoadLogged<USkeletalMesh>(
		TEXT("/Game/Models/Soldier/SM_Soldier/SkeletalMeshes/Body_1b3e0aad2706b303962c73fef1dbefd3.Body_1b3e0aad2706b303962c73fef1dbefd3"),
		TEXT("soldier body"));
	A.SoldierHead = LoadLogged<UStaticMesh>(
		TEXT("/Game/Models/Soldier/SM_Soldier/StaticMeshes/Head_8415018a81766f42d10f7642d4b1c47f.Head_8415018a81766f42d10f7642d4b1c47f"),
		TEXT("soldier head"));
	A.AnimIdle = LoadLogged<UAnimSequence>(
		TEXT("/Game/Models/Soldier/SM_Soldier/SkeletalMeshes/SM_SoldierCharacterArmature_Idle.SM_SoldierCharacterArmature_Idle"),
		TEXT("idle clip"));
	A.AnimRun = LoadLogged<UAnimSequence>(
		TEXT("/Game/Models/Soldier/SM_Soldier/SkeletalMeshes/SM_SoldierCharacterArmature_Run.SM_SoldierCharacterArmature_Run"),
		TEXT("run clip"));
	A.AnimDeath = LoadLogged<UAnimSequence>(
		TEXT("/Game/Models/Soldier/SM_Soldier/SkeletalMeshes/SM_SoldierCharacterArmature_Death.SM_SoldierCharacterArmature_Death"),
		TEXT("death clip"));

	A.HumveeMesh = LoadLogged<UStaticMesh>(
		TEXT("/Game/Models/Humvee/SM_Humvee.SM_Humvee"), TEXT("humvee"));
	A.TruckMesh = LoadLogged<UStaticMesh>(
		TEXT("/Game/Models/TruckM939/SM_TruckM939.SM_TruckM939"), TEXT("truck"));
	A.TankMesh = LoadLogged<UStaticMesh>(
		TEXT("/Game/Models/Tank/SM_Tank.SM_Tank"), TEXT("tank"));
	A.TankTurret = LoadLogged<UStaticMesh>(
		TEXT("/Game/Models/Tank/SM_Tank/StaticMeshes/Tank_Turret.Tank_Turret"),
		TEXT("tank turret"));
	A.CannonMesh = LoadLogged<UStaticMesh>(
		TEXT("/Game/Models/Cannon/SM_Cannon.SM_Cannon"), TEXT("cannon"));
	A.CannonWheels = LoadLogged<UStaticMesh>(
		TEXT("/Game/Models/Cannon/SM_Cannon/StaticMeshes/Cannon_Wheels.Cannon_Wheels"),
		TEXT("cannon wheels"));

	A.UnitBodyMat = LoadLogged<UMaterialInterface>(
		TEXT("/Game/Units/M_UnitBody.M_UnitBody"), TEXT("unit body material"));
	A.PlaceholderMat = LoadLogged<UMaterialInterface>(
		TEXT("/Game/Materials/M_Placeholder.M_Placeholder"), TEXT("placeholder material"));
	A.FxFlashMat = LoadLogged<UMaterialInterface>(
		TEXT("/Game/FX/M_FxFlash.M_FxFlash"), TEXT("flash material"));
	A.FxDirtMat = LoadLogged<UMaterialInterface>(
		TEXT("/Game/FX/M_FxDirt.M_FxDirt"), TEXT("dirt material"));
	A.FxSmokeMat = LoadLogged<UMaterialInterface>(
		TEXT("/Game/FX/M_FxSmoke.M_FxSmoke"), TEXT("smoke material"));

	A.Cube = LoadLogged<UStaticMesh>(TEXT("/Engine/BasicShapes/Cube.Cube"), TEXT("cube"));
	A.Sphere = LoadLogged<UStaticMesh>(TEXT("/Engine/BasicShapes/Sphere.Sphere"), TEXT("sphere"));

	A.bHumanoidReal = (A.SoldierMesh != nullptr);
	A.bAnimsReal = (A.AnimIdle && A.AnimRun && A.AnimDeath);
	UE_LOG(LogShitfire, Log,
		TEXT("units: assets loaded (humanoid %s, anims %s)"),
		A.bHumanoidReal ? TEXT("real") : TEXT("BOX FALLBACK"),
		A.bAnimsReal ? TEXT("real") : TEXT("POSE-ONLY"));
	return A;
}
