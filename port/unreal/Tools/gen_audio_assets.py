"""Imports the radio-net WAVs into /Game/Audio (BUILDER-BRIDGE, P4).

Same regime as gen_assets.py / gen_fx_assets.py: the .uassets are build
products on the allowlist; sources of truth are Tools/audio_src/*.wav
(boom = CC0 recording, see port/CREDITS.md; squelch/hiss generated by
Tools/gen_audio_src.py). Delete + reimport on every run.

  S_BoomDistant   distance-delayed impact boom (played by ShitfireAudio)
  S_SquelchClick  radio squelch cue framing FDC lines (radio DSP baked in)
  S_NetHiss       looping low net-noise bed

Run headless:
  UnrealEditor-Cmd.exe <Shitfire.uproject> -run=pythonscript ^
      -script="port/unreal/Tools/gen_audio_assets.py" -unattended -nopause
"""
import os
import unreal

EAL = unreal.EditorAssetLibrary
TOOLS = unreal.AssetToolsHelpers.get_asset_tools()
PKG_PATH = "/Game/Audio"
SRC = os.path.join(os.path.dirname(os.path.abspath(__file__)), "audio_src")

IMPORTS = [
    ("boom_distant.wav", "S_BoomDistant", False),
    ("squelch_click.wav", "S_SquelchClick", False),
    ("net_hiss_loop.wav", "S_NetHiss", True),
]

for src_name, asset_name, looping in IMPORTS:
    full = "{}/{}".format(PKG_PATH, asset_name)
    if EAL.does_asset_exist(full):
        EAL.delete_asset(full)
    task = unreal.AssetImportTask()
    task.set_editor_property("filename", os.path.join(SRC, src_name))
    task.set_editor_property("destination_path", PKG_PATH)
    task.set_editor_property("destination_name", asset_name)
    task.set_editor_property("automated", True)
    task.set_editor_property("save", True)
    task.set_editor_property("replace_existing", True)
    TOOLS.import_asset_tasks([task])
    sw = EAL.load_asset(full)
    if sw is None:
        raise RuntimeError("import failed for " + full)
    if looping:
        sw.set_editor_property("looping", True)
        EAL.save_loaded_asset(sw)
    unreal.log("gen_audio_assets: wrote " + full)

unreal.log("gen_audio_assets: done")
